        internal void Validate()
        {
            Catalog.ValidateIdentity(id, kind, subject, slot, renderMode);
            Check.That(binding != null && new[] { "sprite-key", "wanted-photo", "scene-key", "custom" }.Contains(binding.type), "Unknown binding");
            Check.That(binding.key == null || Check.Id(binding.key), "Invalid binding key");
            Check.That(binding.type == "custom" || subject.owner == "game" && binding.key == subject.key, "Native identity mismatch");
            if (subject.owner == "game" && NativeClientRoles.IsRoleKey(subject.key)) Check.That(binding.type == "sprite-key", "Occupation requires sprite-key binding");
            if (binding.type == "sprite-key") Check.That(kind == "character" && slot == "main", "Character binding mismatch");
            if (binding.type == "wanted-photo") Check.That(kind == "wanted" && slot == "photo" && Enumerable.Range(1, 9).Any(n => binding.key == "wanted" + n), "Photo binding mismatch");
            if (binding.type == "scene-key") Check.That(kind == "scene" && new[] { "dumping_ground", "drjackson", "drjackson2", "commissary" }.Contains(binding.key) && slot == (binding.key == "drjackson" ? "travel-card" : "background"), "Scene binding mismatch");
            Check.That(candidateResources != null && candidateResources.Length <= 4096 && candidateResources.All(r => r != null), "Candidate references required");
            var refs = new HashSet<string>(StringComparer.Ordinal);
            foreach (var r in candidateResources) { r.Validate(); Check.That(refs.Add(r.Key), "Duplicate candidate reference"); }
            Check.That(defaultMode == "source" && defaultResource == null || defaultMode == "resource" && defaultResource != null, "Invalid default mode"); defaultResource?.Validate();
        }
    }
