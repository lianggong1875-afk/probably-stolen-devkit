    internal static class Check
    {
        public static void That(bool ok, string message, string code = "invalid-message") { if (!ok) throw new ContractException(code, message); }
        public static bool Id(string s) => !string.IsNullOrWhiteSpace(s) && s.Length <= 160;
        public static bool Finite(float f) => !float.IsNaN(f) && !float.IsInfinity(f);
        public static bool Hash(string s) => s != null && s.Length == 64 && s.All(c => c >= '0' && c <= '9' || c >= 'a' && c <= 'f');
        public static T Parse<T>(string json)
        {
            var token = JToken.Parse(json, new JsonLoadSettings { DuplicatePropertyNameHandling = DuplicatePropertyNameHandling.Error });
            Shape(token);
            return token.ToObject<T>(JsonSerializer.Create(new JsonSerializerSettings { MissingMemberHandling = MissingMemberHandling.Error }));
        }
        static readonly HashSet<string> strings = new HashSet<string>(new[] { "format", "contract", "providerId", "renderMode", "role", "catalogRevision", "revision", "id", "name", "kind", "slot", "owner", "key", "type", "defaultMode", "setId", "resourceRevision", "path", "contentHash", "filter", "wrapU", "wrapV", "wrapW", "colorSpace", "mode", "sha256", "meshType" }, StringComparer.Ordinal);
        static readonly HashSet<string> integers = new HashSet<string>(new[] { "width", "height", "anisoLevel", "level", "residentDeltaBytes", "peakAdditionalBytes" }, StringComparer.Ordinal);
        static readonly HashSet<string> numbers = new HashSet<string>(new[] { "pixelsPerUnit", "pivotX", "pivotY", "mipMapBias", "left", "bottom", "right", "top", "scale", "x", "y" }, StringComparer.Ordinal);
        static readonly HashSet<string> arrays = new HashSet<string>(new[] { "resourceSets", "portraitSets", "entries", "targets", "candidateResources", "resources", "levels" }, StringComparer.Ordinal);
        static void Shape(JToken node)
        {
            if (node is JArray array) { foreach (var item in array) { That(item is JObject, "Object array required"); Shape(item); } return; }
            That(node is JObject, "Object required");
            foreach (var p in ((JObject)node).Properties())
            {
                That(p.Value.Type != JTokenType.Null, "Null field is not supported");
                if (strings.Contains(p.Name)) That(p.Value.Type == JTokenType.String, "String required: " + p.Name);
                else if (integers.Contains(p.Name) || (p.Name == "x" || p.Name == "y") && node.Parent is JProperty parent && parent.Name == "rect") That(p.Value.Type == JTokenType.Integer, "Integer required: " + p.Name);
                else if (numbers.Contains(p.Name)) That((p.Value.Type == JTokenType.Integer || p.Value.Type == JTokenType.Float) && !double.IsNaN((double)p.Value) && !double.IsInfinity((double)p.Value), "Finite number required: " + p.Name);
                else if (arrays.Contains(p.Name)) { That(p.Value is JArray, "Array required: " + p.Name); Shape(p.Value); }
                else Shape(p.Value);
            }
        }
    }
