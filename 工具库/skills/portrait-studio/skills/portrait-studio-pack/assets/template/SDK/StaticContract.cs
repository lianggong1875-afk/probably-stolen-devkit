    {
        [JsonRequired] public string id, kind, slot, renderMode;
        [JsonRequired] public Subject subject;
        [JsonRequired] public Asset[] resources;
        [JsonIgnore] public string Identity => Catalog.Identity(kind, subject, slot);
        readonly Dictionary<string, Asset> index = new Dictionary<string, Asset>(StringComparer.Ordinal);
        internal void Index(string root)
        {
            Catalog.ValidateIdentity(id, kind, subject, slot, renderMode);
            Check.That(resources != null && resources.Length > 0 && resources.Length <= 4096, "Resources required");
            foreach (var a in resources)
            {
                Check.That(a != null && Check.Id(a.id) && Check.Id(a.resourceRevision) && a.renderMode == "static" && a.texture != null && a.geometry != null, "Explicit static resource required");
                Catalog.PngPath(root, a.path); a.texture.Validate(root); a.geometry.Validate(a.texture.width, a.texture.height);
                var k = JsonConvert.SerializeObject(new[] { a.id, a.resourceRevision });
                Check.That(!index.ContainsKey(k), "Duplicate resource revision"); index.Add(k, a);
            }
        }
        public Asset GetAsset(string id, string revision)
        {
            Check.That(index.TryGetValue(JsonConvert.SerializeObject(new[] { id, revision }), out var a), "Resource revision missing", "resource-missing"); return a;
        }
