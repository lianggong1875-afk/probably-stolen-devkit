    public sealed class TextureInfo
    {
        [JsonRequired] public int width, height, anisoLevel;
        [JsonRequired] public string contentHash, filter, wrapU, wrapV, wrapW, colorSpace;
        [JsonRequired] public float mipMapBias;
        [JsonRequired] public MipMaps mipmaps;
        internal void Validate(string root)
        {
            Check.That(width > 0 && height > 0 && width <= 8192 && height <= 8192 && (long)width * height <= 16777216 && Check.Hash(contentHash), "Invalid texture dimensions/hash");
            Check.That(new[] { "Point", "Bilinear", "Trilinear" }.Contains(filter) && new[] { wrapU, wrapV, wrapW }.All(v => new[] { "Clamp", "Repeat", "Mirror", "MirrorOnce" }.Contains(v)) && anisoLevel >= 0 && anisoLevel <= 16 && Check.Finite(mipMapBias) && (colorSpace == "sRGB" || colorSpace == "linear"), "Invalid sampling/color space");
            Check.That(mipmaps != null && new[] { "none", "generate", "provided" }.Contains(mipmaps.mode), "Explicit mip mode required");
            if (mipmaps.mode != "provided") { Check.That(mipmaps.levels == null, "Unexpected mip levels"); return; }
            int w = width, h = height, i = 0;
            Check.That(mipmaps.levels != null && mipmaps.levels.Length > 0 && mipmaps.levels.Length <= 13, "Mip chain required");
            foreach (var m in mipmaps.levels)
            {
                Check.That(w > 1 || h > 1, "Excess mip levels"); w = Math.Max(1, w / 2); h = Math.Max(1, h / 2);
                Check.That(m != null && m.level == ++i && m.width == w && m.height == h && Check.Hash(m.sha256), "Invalid mip chain");
                Catalog.PngPath(root, m.path);
            }
            Check.That(w == 1 && h == 1, "Mip chain must end at 1x1");
        }
    }
