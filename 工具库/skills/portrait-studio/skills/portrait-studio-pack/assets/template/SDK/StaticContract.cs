    public sealed class Catalog
    {
        public const string Format = "portrait-studio-static/1", Contract = "static-display-transaction/1", FileName = "portrait-studio-provider.json";
        [JsonRequired] public string format, contract, providerId, renderMode, role, catalogRevision;
        [JsonRequired] public ResourceSet[] resourceSets;
        public PortraitSet[] portraitSets;
        public string revision;
        public Target[] targets;
        readonly Dictionary<string, Target> targetIndex = new Dictionary<string, Target>(StringComparer.Ordinal);
        readonly Dictionary<string, ResourceSet> setIndex = new Dictionary<string, ResourceSet>(StringComparer.Ordinal);
        public Target GetTarget(string id) => targetIndex[id];
        public ResourceSet GetSet(string id) { Check.That(setIndex.TryGetValue(id, out var s), "Resource set missing", "resource-missing"); return s; }
        public PortraitSet GetPortraitSet(string id)
        {
            var set = portraitSets?.FirstOrDefault(s => s.id == id);
            Check.That(set != null, "Portrait set missing", "resource-missing"); return set;
        }
        internal static string Identity(string kind, Subject subject, string slot) => JsonConvert.SerializeObject(new[] { kind, subject?.owner, subject?.key, slot });
        internal static void ValidateIdentity(string id, string kind, Subject subject, string slot, string mode)
        {
            Check.That(Check.Id(id) && subject != null && Check.Id(subject.owner) && Check.Id(subject.key) && Check.Id(slot) && new[] { "character", "wanted", "scene" }.Contains(kind) && mode == "static", "Explicit static identity required");
            NativeClientRoles.Validate(kind, subject, slot);
        }
        public static Catalog Read(string root, string expectedId)
        {
            var path = SafePath(root, FileName); Check.That(new FileInfo(path).Length <= 1048576, "Catalog exceeds 1 MiB");
            var text = File.ReadAllText(path);
            var raw = JObject.Parse(text);
            if ((string)raw["role"] == "resources") Check.That(raw["revision"] == null && raw["targets"] == null, "Resource provider must not contain writer fields");
            if (raw["targets"] is JArray targetRows) foreach (JObject targetRow in targetRows)
                if ((string)targetRow["defaultMode"] == "source") Check.That(targetRow["defaultResource"] == null, "Source default forbids resource field");
            var c = Check.Parse<Catalog>(text);
            Check.That(c != null && c.format == Format && c.contract == Contract && c.providerId == expectedId && Check.Id(c.providerId) && c.renderMode == "static" && Check.Id(c.catalogRevision), "Explicit contract/static catalog required");
            Check.That(new[] { "writer", "resources", "both" }.Contains(c.role) && c.resourceSets != null && c.resourceSets.Length <= 4096, "Invalid catalog role/sets");
            foreach (var s in c.resourceSets) { Check.That(s != null && !c.setIndex.ContainsKey(s.id ?? ""), "Duplicate/missing set"); s.Index(root); c.setIndex.Add(s.id, s); }
            c.ValidatePortraitSets();
            if (c.role == "resources") { Check.That(c.targets == null && c.revision == null, "Resource provider must not advertise writer"); return c; }
            Check.That(Check.Id(c.revision) && c.targets != null && c.targets.Length > 0 && c.targets.Length <= 4096, "Writer targets/revision required");
            var identities = new HashSet<string>(StringComparer.Ordinal);
            foreach (var t in c.targets)
            {
                Check.That(t != null && !c.targetIndex.ContainsKey(t.id ?? ""), "Duplicate/missing target"); t.Validate();
                Check.That(identities.Add(t.Identity), "Duplicate writer display identity"); c.targetIndex.Add(t.id, t);
                foreach (var r in t.candidateResources.Concat(t.defaultResource == null ? Array.Empty<ResourceRef>() : new[] { t.defaultResource }))
                    if (r.providerId == c.providerId) { var s = c.GetSet(r.setId); Check.That(s.Identity == t.Identity, "Resource display identity mismatch", "identity-mismatch"); s.GetAsset(r.id, r.revision); }
            }
            c.ValidatePortraitSetTargets(c.targets);
            return c;
        }
        void ValidatePortraitSets()
        {
            if (portraitSets == null) return;
            Check.That(portraitSets.Length > 0 && portraitSets.Length <= 128, "Portrait sets must contain 1..128 collections");
            var ids = new HashSet<string>(StringComparer.Ordinal);
            foreach (var s in portraitSets)
            {
                Check.That(s != null && Check.Id(s.id) && Check.Id(s.name) && s.renderMode == "static" && ids.Add(s.id), "Invalid/duplicate static portrait set");
                Check.That(s.entries != null && s.entries.Length > 0 && s.entries.Length <= 4096, "Portrait set entries required");
                var identities = new HashSet<string>(StringComparer.Ordinal);
                foreach (var r in s.entries)
                {
                    Check.That(r != null, "Portrait set resource required"); r.Validate();
                    Check.That(r.providerId == providerId, "Portrait set resources must be local");
                    var group = GetSet(r.setId); group.GetAsset(r.id, r.revision);
                    Check.That(identities.Add(group.Identity), "Portrait set contains duplicate display identity");
                }
            }
        }
        // Writers and managed declarations use the same check; resource-only catalogs need no target.
        public void ValidatePortraitSetTargets(IEnumerable<Target> declaredTargets)
        {
            if (portraitSets == null) return;
            var targetsByIdentity = declaredTargets.ToDictionary(t => t.Identity, StringComparer.Ordinal);
            foreach (var s in portraitSets) foreach (var r in s.entries)
            {
                var identity = GetSet(r.setId).Identity;
                Check.That(targetsByIdentity.TryGetValue(identity, out var t) && t.candidateResources.Any(candidate => candidate.Key == r.Key), "Portrait set entry must be a declared target candidate");
            }
        }
        internal static string PngPath(string root, string relative)
        {
            Check.That(relative != null && relative.Length <= 512 && relative.EndsWith(".png", StringComparison.OrdinalIgnoreCase), "PNG required"); return SafePath(root, relative);
        }
        public static string SafePath(string root, string relative)
        {
            Check.That(!string.IsNullOrWhiteSpace(root), "Provider folder unavailable; initialize after the loader registers the mod (first frame or later)", "resource-missing");
            Check.That(!string.IsNullOrWhiteSpace(relative) && !relative.Contains("\\") && !relative.Contains(":") && !relative.StartsWith("/") && !relative.Split('/').Any(p => p == ".." || p == "." || p.Length == 0), "Unsafe relative path");
            root = Path.GetFullPath(root).TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
            var path = Path.GetFullPath(Path.Combine(root, relative));
            Check.That(path.StartsWith(root + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase), "Path escaped mod");
            for (var d = new FileInfo(path) as FileSystemInfo; d != null; d = d is FileInfo f ? f.Directory : ((DirectoryInfo)d).Parent)
                Check.That(!d.Exists || (d.Attributes & FileAttributes.ReparsePoint) == 0, "Linked paths rejected");
            return path;
        }
    }
